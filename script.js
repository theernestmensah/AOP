/*  KEYBOARD ACCESSIBILITY + MODAL CLOSE  */
document.addEventListener('keydown', e => {
    if (e.key !== 'Escape') return;
    // Close mobile nav menu
    if (navLinksMenu?.classList.contains('open')) closeMenu();
    // Close order success modal (delegates to the order platform handler)
    const orderModal = document.getElementById('order-modal');
    if (orderModal?.classList.contains('open')) {
        if (typeof window.globalCloseOrderModal === 'function') {
            window.globalCloseOrderModal(true);
        } else {
            orderModal.classList.remove('open');
            document.body.style.overflow = '';
        }
    }
});

/* ============================================================
   SERVICES PAGE: SWITCH SERVICE CATEGORY
   ============================================================ */
function switchServiceCategory(category) {
    const printSection = document.getElementById('printing-section');
    const booksSection = document.getElementById('books-section');
    const btnPrint = document.getElementById('btn-printing');
    const btnBooks = document.getElementById('btn-books');

    if (!printSection || !booksSection) return;

    const navHeight = document.getElementById('navbar') ? document.getElementById('navbar').offsetHeight : 80;

    if (category === 'printing') {
        printSection.style.display = 'block';
        setTimeout(() => printSection.classList.add('active'), 50);
        booksSection.style.display = 'none';
        booksSection.classList.remove('active');

        btnPrint.classList.add('active-split');
        btnBooks.classList.remove('active-split');

        setTimeout(() => {
            const targetPos = printSection.getBoundingClientRect().top + window.scrollY - navHeight - 30;
            window.scrollTo({ top: targetPos, behavior: 'smooth' });
        }, 300);

    } else if (category === 'books') {
        booksSection.style.display = 'block';
        setTimeout(() => booksSection.classList.add('active'), 50);
        printSection.style.display = 'none';
        printSection.classList.remove('active');

        btnBooks.classList.add('active-split');
        btnPrint.classList.remove('active-split');

        setTimeout(() => {
            const targetPos = booksSection.getBoundingClientRect().top + window.scrollY - navHeight - 30;
            window.scrollTo({ top: targetPos, behavior: 'smooth' });
        }, 300);
    }
}



