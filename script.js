function initTestimonialsSlider() {
    const track = document.getElementById('testimonial-track');
    const dotsWrap = document.getElementById('slider-dots');
    const prevBtn = document.getElementById('slider-prev');
    const nextBtn = document.getElementById('slider-next');
    if (!track) return;

    const cards = track.querySelectorAll('.testimonial-card');
    let current = 0;
    let total = 0;
    let perView = 1;

    function buildSlider() {
        perView = window.innerWidth <= 900 ? 1 : 2;
        total = Math.ceil(cards.length / perView);

        // Recreate dots
        if (dotsWrap) {
            dotsWrap.innerHTML = '';
            for (let i = 0; i < total; i++) {
                const dot = document.createElement('button');
                dot.className = 'slider-dot' + (i === 0 ? ' active' : '');
                dot.setAttribute('aria-label', `Go to slide ${i + 1}`);
                dot.addEventListener('click', () => { goTo(i); });
                dotsWrap.appendChild(dot);
            }
        }
        goTo(0);
    }

    function goTo(index) {
        if (total === 0) return;
        current = Math.max(0, Math.min(index, total - 1));
        const cardWidth = cards[0].offsetWidth + 24; // including flex gap
        const offset = current * cardWidth * perView;
        track.style.transform = `translateX(-${offset}px)`;

        if (dotsWrap) {
            dotsWrap.querySelectorAll('.slider-dot').forEach((d, i) => {
                d.classList.toggle('active', i === current);
            });
        }
    }

    if (prevBtn) {
        // clone and replace to remove old listeners just in case
        prevBtn.replaceWith(prevBtn.cloneNode(true));
        document.getElementById('slider-prev').addEventListener('click', () => { goTo(current === 0 ? total - 1 : current - 1); });
    }
    if (nextBtn) {
        nextBtn.replaceWith(nextBtn.cloneNode(true));
        document.getElementById('slider-next').addEventListener('click', () => { goTo(current === total - 1 ? 0 : current + 1); });
    }

    buildSlider();

    let resizeTimer;
    window.addEventListener('resize', () => {
        clearTimeout(resizeTimer);
        resizeTimer = setTimeout(() => {
            buildSlider();
        }, 150);
    });
}
document.addEventListener('DOMContentLoaded', initTestimonialsSlider);

